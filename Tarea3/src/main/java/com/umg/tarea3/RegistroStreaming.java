    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // Variables locales solo del artista
        String nombre = txtNombre.getText();
        String pais = txtPais.getText();
        int oyentes = Integer.parseInt(txtOyentes.getText());

        // Crear el objeto y asignar los valores con el punto
        Artista a = new Artista();
        a.nombre = nombre;
        a.paisOrigen = pais;
        a.oyentesMensuales = oyentes;

        // Mostrar en el area de texto sin borrar lo anterior
        taResultados.append("ARTISTA: " + a.nombre + " | País: " + a.paisOrigen
                + " | Oyentes: " + a.oyentesMensuales + "\n");

        txtNombre.setText("");
        txtPais.setText("");
        txtOyentes.setText("");
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // Variables locales solo de la cancion
        String titulo = txtTitulo.getText();
        String interprete = txtInterprete.getText();
        int duracion = Integer.parseInt(txtDuracion.getText());
        String genero = txtGenero.getText();

        Cancion c = new Cancion();
        c.titulo = titulo;
        c.nombreArtista = interprete;
        c.duracionSegundos = duracion;
        c.genero = genero;

        taResultados.append("CANCIÓN: " + c.titulo + " | Artista: " + c.nombreArtista
                + " | Duración: " + c.duracionSegundos + " seg | Género: " + c.genero + "\n");

        txtTitulo.setText("");
        txtInterprete.setText("");
        txtDuracion.setText("");
        txtGenero.setText("");
    }//GEN-LAST:event_btnCrearCancionActionPerformed

