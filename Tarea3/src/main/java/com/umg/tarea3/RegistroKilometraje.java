    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // Guarda el numero en el arreglo (lunes a domingo)
        if (indice < 7) {
            rutas[indice] = Double.parseDouble(txtKilometraje.getText());
            indice++;
            txtKilometraje.setText("");
            JOptionPane.showMessageDialog(this, "Ruta " + indice + " agregada");
        } else {
            JOptionPane.showMessageDialog(this, "Ya se ingresaron las 7 rutas");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        // Falta ingresar rutas
        if (indice < 7) {
            JOptionPane.showMessageDialog(this, "Faltan rutas por ingresar");
            return;
        }

        // Recorrer el arreglo para sacar el total
        double total = 0;
        for (int i = 0; i < 7; i++) {
            total = total + rutas[i];
        }
        double promedio = total / 7;
        promedio = Math.round(promedio * 100) / 100.0;

        // Escribir el reporte en la carpeta temp
        String ubicacion = "temp/";
        try {
            FileWriter fw = new FileWriter(ubicacion + "andru_reporte_rutas.txt");
            fw.write("Reporte Semanal de Rutas\n");
            fw.write("Total de Kilómetros: " + total + "\n");
            fw.write("Promedio Diario: " + promedio + "\n");
            fw.close();
            JOptionPane.showMessageDialog(this, "Reporte generado");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnGenerarActionPerformed

