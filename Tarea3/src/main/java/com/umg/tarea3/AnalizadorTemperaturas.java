    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // Leer el archivo linea por linea
        try {
            File archivo = new File(ruta);
            Scanner sc = new Scanner(archivo);
            indice = 0;
            while (sc.hasNextLine()) {
                String linea = sc.nextLine();
                temperaturas[indice] = Double.parseDouble(linea);
                indice++;
            }
            sc.close();
            JOptionPane.showMessageDialog(this, "Los datos fueron cargados en memoria");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        if (indice == 0) {
            JOptionPane.showMessageDialog(this, "Primero carga los datos");
            return;
        }

        double suma = 0;
        int calidos = 0;
        int frescos = 0;

        for (int i = 0; i < temperaturas.length; i++) {
            suma = suma + temperaturas[i];
            if (temperaturas[i] >= 25.0) {
                calidos++;
            } else {
                frescos++;
            }
        }
        double promedio = suma / temperaturas.length;
        promedio = Math.round(promedio * 100) / 100.0;

        taResultados.setText("Análisis Climático\n");
        taResultados.append("------------------\n");
        taResultados.append("Promedio de Temperatura: " + promedio + "\n");
        taResultados.append("Días Cálidos (>= 25°): " + calidos + "\n");
        taResultados.append("Días Frescos (< 25°): " + frescos + "\n");
    }//GEN-LAST:event_btnCalcularActionPerformed

