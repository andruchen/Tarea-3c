    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String titulo = txtTitulo.getText();
        String consola = txtConsola.getText();
        int anio = Integer.parseInt(txtAnio.getText());

        // crear el objeto con el constructor y guardarlo en la lista
        Videojuego v = new Videojuego(titulo, consola, anio);
        catalogo.add(v);

        txtTitulo.setText("");
        txtConsola.setText("");
        txtAnio.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
        taInventario.setText("");
        for (int i = 0; i < catalogo.size(); i++) {
            Videojuego v = catalogo.get(i);
            taInventario.append((i + 1) + ". " + v.titulo + " - " + v.consola
                    + " - " + v.anioLanzamiento + "\n");
        }
        taInventario.append("\nTotal de juegos: " + catalogo.size());
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (catalogo.size() > 0) {
            catalogo.remove(catalogo.size() - 1);
            JOptionPane.showMessageDialog(this, "Se eliminó el último juego");
        } else {
            JOptionPane.showMessageDialog(this, "No hay juegos en el catálogo");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

