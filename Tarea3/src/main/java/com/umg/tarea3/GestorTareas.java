    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // Guardar la tarea en el arreglo y mostrarla en el area de texto
        if (indice < 5) {
            tareas[indice] = txtTarea.getText();
            taListado.append((indice + 1) + ". " + tareas[indice] + "\n");
            indice++;

            //Limpia el texto de notas luego de agregado al arreglo
            txtTarea.setText("");
            //Crear una ventana de mensaje
            JOptionPane.showMessageDialog(this, "Tarea " + indice + " agregada");
        } else {
            JOptionPane.showMessageDialog(this, "Ya se ingresaron las 5 tareas");
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // Solo se puede exportar cuando ya estan las 5 tareas
        if (indice < 5) {
            JOptionPane.showMessageDialog(this, "Faltan tareas por ingresar");
            return;
        }

        //No cambiar la ubicacion, esto creará el archivo dentro de la carpeta temp que esta en el proyecto
        String ubicacion = "temp/";

        try {
            FileWriter fw = new FileWriter(ubicacion + "andru_agenda.txt");
            fw.write("Agenda de Tareas\n");
            for (int i = 0; i < 5; i++) {
                fw.write((i + 1) + ". " + tareas[i] + "\n");
            }
            fw.close();
            JOptionPane.showMessageDialog(this, "Agenda exportada");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnExportarActionPerformed

